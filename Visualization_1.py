# 6. Interactive genre comparison
# --------------------------------------------------------------------------
@app.callback(
    Output("genre-table", "data"),
    Output("genre-summary", "children"),
    Input("genre-selector", "value"),
)
def update_genre_comparison(selected_genres):

    if not selected_genres:
        return [], "Select at least one genre to compare."

    filtered = genre_indicators[
        genre_indicators["track_genre"].isin(selected_genres)
    ].copy()

    numeric_cols = filtered.select_dtypes(
        include="number"
    ).columns

    filtered[numeric_cols] = filtered[numeric_cols].round(2)

    summary = html.P(
        f"Comparing {len(filtered)} selected genres."
    )

    return filtered[table_columns].to_dict("records"), summary


